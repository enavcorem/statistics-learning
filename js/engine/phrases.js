// 'f' | 'm' | 'p'. gender = מה שהתלמיד/ה בחר/ה; בקורס `voice: 'plural'` תמיד 'p'.
export function voice(gender) {
  if (PLURAL_VOICE) return 'p';
  return gender === 'm' ? 'm' : 'f';
}

export function t(key, gender) {
  const entry = PHRASES[key];
  if (!entry) { console.warn('phrase missing:', key); return ''; }
  const v = voice(gender);
  return entry[v] || entry.f || '';
}

// הלשון של התלמיד/ה המחוברת עכשיו (בתצוגת מורה: מה שנבחר במתג).
export function tv(key) {
  const s = Progress.getStudent();
  return t(key, s && s.gender);
}
