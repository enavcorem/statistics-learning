// אחר, נופלים לנקבה (עדיף לכתוב p במניפסט).
function welcomeEntry() {
  const w = COURSE.welcome || {};
  const p = w.p || (w.f ? w.f.replace('ברוכה הבאה', 'ברוכים הבאים').replace('ברוכות הבאות', 'ברוכים הבאים') : '');
  return { f: w.f, m: w.m, p };
}

