// ===== רמז גלילה למסך הבית =====
// כשמסיימים יחידה/פרק ומנווטים חזרה ל-#roadmap, הדף נבנה מחדש לגמרי,
// ובלי עזרה הדפדפן משאיר את מיקום הגלילה הישן — שנופל במקרה איפשהו על
// הדף החדש (למשל "באמצע פרק 4"), לא במקום הרלוונטי. מי שמסיים יחידה/פרק
// קובע כאן *לאן* לגלול לפני הניווט, ו-roadmap-render צורך את זה פעם אחת.

let hint = null;

// { type: 'unit', id } → למרכז את כרטיס היחידה הבאה (סיום שיעור/מעבדה/מבחן רגיל)
// { type: 'chapter', id } → למרכז את "באנר" הפרק הבא (סיום אתגר-פטור שעבר, או
//                            סיום היחידה האחרונה בפרק שחצתה לפרק הבא)
export function setRoadmapScrollHint(nextHint) {
  hint = nextHint;
}

export function consumeRoadmapScrollHint() {
  const h = hint;
  hint = null;
  return h;
}
